-- ============================================================================
-- TABLE: Daily_Dish_Preparation
-- Purpose:
-- Stores the daily preparation details for each dish.
-- One record represents the quantity of a dish prepared on a particular day.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Daily_Dish_Preparation
(
    dish_id                 INT,
    preparation_date        DATE NOT NULL DEFAULT CURRENT_DATE,

    prepared_quantity       INT NOT NULL,
    remaining_quantity      INT NOT NULL,

    CONSTRAINT pk_daily_dish_preparation
        PRIMARY KEY (dish_id, preparation_date),

    CONSTRAINT chk_prepared_quantity
        CHECK (prepared_quantity > 0),

    CONSTRAINT chk_remaining_quantity
        CHECK
        (
            remaining_quantity >= 0
            AND remaining_quantity <= prepared_quantity
        ),

    CONSTRAINT fk_daily_preparation_dish
        FOREIGN KEY (dish_id)
        REFERENCES Dish(dish_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);



