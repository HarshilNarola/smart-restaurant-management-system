-- ============================================================================
-- TABLE: Orders
-- Purpose: Stores all customer orders.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Orders
(
    order_id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_date_time      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status               VARCHAR(20) NOT NULL DEFAULT 'Pending',

    customer_id          INT NOT NULL,
    employee_id          INT NOT NULL,
    table_number         INT NOT NULL,

    CONSTRAINT pk_orders
        PRIMARY KEY (order_id),

    CONSTRAINT chk_order_status
        CHECK (
            status IN
            (
                'Pending',
                'Preparing',
                'Served',
                'Completed',
                'Cancelled'
            )
        ),

    CONSTRAINT fk_order_customer
        FOREIGN KEY (customer_id)
        REFERENCES Customer(customer_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT fk_order_employee
        FOREIGN KEY (employee_id)
        REFERENCES Employee(employee_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT fk_order_restaurant_table
        FOREIGN KEY (table_number)
        REFERENCES Restaurant_Table(table_number)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);



-- ============================================================================
-- TABLE: Bill
-- Purpose: Stores billing information for each order.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Bill
(
    bill_id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    bill_date_time       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    subtotal             DECIMAL(10,2) NOT NULL,
    tax                  DECIMAL(10,2) NOT NULL,
    discount             DECIMAL(10,2) NOT NULL DEFAULT 0,
    total_amount         DECIMAL(10,2) NOT NULL,

    payment_mode         VARCHAR(20) NOT NULL,
    payment_status       VARCHAR(20) NOT NULL DEFAULT 'Pending',

    order_id             BIGINT NOT NULL,

    CONSTRAINT pk_bill
        PRIMARY KEY (bill_id),

    CONSTRAINT uq_bill_order
        UNIQUE (order_id),

    CONSTRAINT chk_bill_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT chk_bill_tax
        CHECK (tax >= 0),

    CONSTRAINT chk_bill_discount
        CHECK
        (
            discount >= 0
            AND discount <= subtotal
        ),

    CONSTRAINT chk_bill_total_amount
        CHECK (total_amount >= 0),

    CONSTRAINT chk_bill_payment_mode
        CHECK
        (
            payment_mode IN
            (
                'Cash',
                'UPI',
                'Card'
            )
        ),

    CONSTRAINT chk_bill_payment_status
        CHECK
        (
            payment_status IN
            (
                'Pending',
                'Paid'
            )
        ),

    CONSTRAINT fk_bill_order
        FOREIGN KEY (order_id)
        REFERENCES Orders(order_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);



-- ============================================================================
-- TABLE: Purchase
-- Purpose: Stores supplier purchase transactions.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Purchase
(
    purchase_id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    purchase_date_time      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_date_time       TIMESTAMP,

    invoice_number          VARCHAR(50) NOT NULL,
    total_amount            DECIMAL(10,2) NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'Ordered',

    supplier_id             INT NOT NULL,

    CONSTRAINT pk_purchase
        PRIMARY KEY (purchase_id),

    CONSTRAINT uq_purchase_invoice
        UNIQUE (invoice_number),

    CONSTRAINT chk_purchase_invoice
        CHECK
        (
            LENGTH(TRIM(invoice_number)) > 0
        ),

    CONSTRAINT chk_purchase_total_amount
        CHECK
        (
            total_amount >= 0
        ),

    CONSTRAINT chk_purchase_status
        CHECK
        (
            status IN
            (
                'Ordered',
                'Delivered',
                'Cancelled'
            )
        ),

    CONSTRAINT fk_purchase_supplier
        FOREIGN KEY (supplier_id)
        REFERENCES Supplier(supplier_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);



