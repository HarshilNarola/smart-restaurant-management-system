-- ============================================================================
-- TABLE: Dish_Recipe
-- Purpose:
-- Stores the recipe of each dish by specifying the quantity of each
-- raw material required to prepare one serving of the dish.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Dish_Recipe
(
    dish_id                 INT,
    material_id             INT,
    quantity_required       DECIMAL(10,2) NOT NULL,

    CONSTRAINT pk_dish_recipe
        PRIMARY KEY (dish_id, material_id),

    CONSTRAINT chk_quantity_required
        CHECK (quantity_required > 0),

    CONSTRAINT fk_recipe_dish
        FOREIGN KEY (dish_id)
        REFERENCES Dish(dish_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT fk_recipe_material
        FOREIGN KEY (material_id)
        REFERENCES Raw_Material(material_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);



-- ============================================================================
-- TABLE: Supplier_Raw_Material
-- Purpose:
-- Represents which suppliers supply which raw materials.
-- Implements the many-to-many relationship between Supplier and Raw_Material.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Supplier_Raw_Material
(
    supplier_id             INT,
    material_id             INT,

    CONSTRAINT pk_supplier_raw_material
        PRIMARY KEY (supplier_id, material_id),

    CONSTRAINT fk_supplier_material_supplier
        FOREIGN KEY (supplier_id)
        REFERENCES Supplier(supplier_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT fk_supplier_material_raw_material
        FOREIGN KEY (material_id)
        REFERENCES Raw_Material(material_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);



-- ============================================================================
-- TABLE: Order_Item
-- Purpose:
-- Stores all dishes included in an order along with the ordered quantity.
-- Implements the many-to-many relationship between Orders and Dish.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Order_Item
(
    order_id                BIGINT,
    dish_id                 INT,
    quantity                INT NOT NULL,

    CONSTRAINT pk_order_item
        PRIMARY KEY (order_id, dish_id),

    CONSTRAINT chk_order_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT fk_order_item_order
        FOREIGN KEY (order_id)
        REFERENCES Orders(order_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT fk_order_item_dish
        FOREIGN KEY (dish_id)
        REFERENCES Dish(dish_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);



-- ============================================================================
-- TABLE: Purchase_Item
-- Purpose:
-- Stores the raw materials included in a purchase along with their
-- purchased quantity and unit price.
-- Implements the many-to-many relationship between Purchase and
-- Raw_Material.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Purchase_Item
(
    purchase_id             BIGINT,
    material_id             INT,
    quantity                DECIMAL(10,2) NOT NULL,
    unit_price              DECIMAL(10,2) NOT NULL,

    CONSTRAINT pk_purchase_item
        PRIMARY KEY (purchase_id, material_id),

    CONSTRAINT chk_purchase_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_purchase_item_unit_price
        CHECK (unit_price >= 0),

    CONSTRAINT fk_purchase_item_purchase
        FOREIGN KEY (purchase_id)
        REFERENCES Purchase(purchase_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT fk_purchase_item_material
        FOREIGN KEY (material_id)
        REFERENCES Raw_Material(material_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);
