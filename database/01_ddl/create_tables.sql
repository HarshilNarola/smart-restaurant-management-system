-- ============================================================================
-- TABLE: Customer
-- Purpose: Stores customer information.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Customer
(
    customer_id        INT GENERATED BY DEFAULT AS IDENTITY,
    name               VARCHAR(100) NOT NULL,
    mobile_number      VARCHAR(15)  NOT NULL,
    created_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_customer
        PRIMARY KEY (customer_id),

    CONSTRAINT uq_customer_mobile_number
        UNIQUE (mobile_number),

    CONSTRAINT chk_customer_mobile_number
        CHECK (mobile_number ~ '^[0-9]{10}$')
);



-- ============================================================================
-- TABLE: Employee
-- Purpose: Stores employee information.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Employee
(
    employee_id        INT GENERATED BY DEFAULT AS IDENTITY,
    name               VARCHAR(100) NOT NULL,
    phone_number       VARCHAR(15)  NOT NULL,
    role               VARCHAR(50)  NOT NULL,
    salary             DECIMAL(10,2) NOT NULL,
    hire_date          DATE         NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'Active',
    manager_id         INT,

    CONSTRAINT pk_employee
        PRIMARY KEY (employee_id),

    CONSTRAINT uq_employee_phone_number
        UNIQUE (phone_number),

    CONSTRAINT chk_employee_phone_number
        CHECK (phone_number ~ '^[0-9]{10}$'),

    CONSTRAINT chk_employee_salary
        CHECK (salary >= 0),

    CONSTRAINT chk_employee_role
        CHECK (role IN ('Manager','Cashier','Chef','Waiter')),

    CONSTRAINT chk_employee_status
        CHECK (status IN ('Active','Inactive')),

    CONSTRAINT fk_employee_manager
        FOREIGN KEY (manager_id)
        REFERENCES Employee(employee_id)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);



-- ============================================================================
-- TABLE: Restaurant_Table
-- Purpose: Stores information about restaurant tables.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Restaurant_Table
(
    table_number       INT,
    capacity           INT NOT NULL,
    status             VARCHAR(20) NOT NULL DEFAULT 'Available',

    CONSTRAINT pk_restaurant_table
        PRIMARY KEY (table_number),

    CONSTRAINT chk_table_capacity
        CHECK (capacity > 0),

    CONSTRAINT chk_table_status
        CHECK (status IN ('Available','Occupied','Reserved'))
);



-- ============================================================================
-- TABLE: Category
-- Purpose: Stores dish categories.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Category
(
    category_name      VARCHAR(50),

    CONSTRAINT pk_category
        PRIMARY KEY (category_name),

    CONSTRAINT chk_category_name
        CHECK (LENGTH(TRIM(category_name)) > 0)
);



-- ============================================================================
-- TABLE: Dish
-- Purpose: Stores all dishes available in the restaurant.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Dish
(
    dish_id            INT GENERATED BY DEFAULT AS IDENTITY,
    dish_name          VARCHAR(100) NOT NULL,
    price              DECIMAL(10,2) NOT NULL,
    status             VARCHAR(20) NOT NULL DEFAULT 'Available',
    category_name      VARCHAR(50) NOT NULL,

    CONSTRAINT pk_dish
        PRIMARY KEY (dish_id),

    CONSTRAINT uq_dish_name
        UNIQUE (dish_name),

    CONSTRAINT chk_dish_name
        CHECK (LENGTH(TRIM(dish_name)) > 0),

    CONSTRAINT chk_dish_price
        CHECK (price >= 0),

    CONSTRAINT chk_dish_status
        CHECK (status IN ('Available','Unavailable')),

    CONSTRAINT fk_dish_category
        FOREIGN KEY (category_name)
        REFERENCES Category(category_name)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);



-- ============================================================================
-- TABLE: Raw_Material
-- Purpose: Stores inventory of raw materials.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Raw_Material
(
    material_id        INT GENERATED BY DEFAULT AS IDENTITY,
    material_name      VARCHAR(100) NOT NULL,
    current_stock      DECIMAL(10,2) NOT NULL DEFAULT 0,
    unit               VARCHAR(20) NOT NULL,
    minimum_stock      DECIMAL(10,2) NOT NULL,

    CONSTRAINT pk_raw_material
        PRIMARY KEY (material_id),

    CONSTRAINT uq_material_name
        UNIQUE (material_name),

    CONSTRAINT chk_material_name
        CHECK (LENGTH(TRIM(material_name)) > 0),

    CONSTRAINT chk_current_stock
        CHECK (current_stock >= 0),

    CONSTRAINT chk_minimum_stock
        CHECK (minimum_stock >= 0),

    CONSTRAINT chk_material_unit
        CHECK (unit IN ('kg','g','l','ml','pcs','pack'))
);



-- ============================================================================
-- TABLE: Supplier
-- Purpose: Stores supplier information.
-- ============================================================================

CREATE TABLE IF NOT EXISTS Supplier
(
    supplier_id        INT GENERATED BY DEFAULT AS IDENTITY,
    supplier_name      VARCHAR(100) NOT NULL,
    contact_person     VARCHAR(100) NOT NULL,
    phone_number       VARCHAR(15) NOT NULL,
    address            VARCHAR(200) NOT NULL,

    CONSTRAINT pk_supplier
        PRIMARY KEY (supplier_id),

    CONSTRAINT uq_supplier_phone_number
        UNIQUE (phone_number),

    CONSTRAINT chk_supplier_phone_number
        CHECK (phone_number ~ '^[0-9]{10}$'),

    CONSTRAINT chk_supplier_name
        CHECK (LENGTH(TRIM(supplier_name)) > 0),

    CONSTRAINT chk_contact_person
        CHECK (LENGTH(TRIM(contact_person)) > 0),

    CONSTRAINT chk_supplier_address
        CHECK (LENGTH(TRIM(address)) > 0)
);



